export function getCard(id: CardCatalogId): CardDef {
  const card = CARD_CATALOG[id];
  if (!card) throw new Error(`Unknown card: ${id}`);
  return { ...card, targets: [...card.targets] };
}

/** Resolve catalog ids into a fresh CardDef array for a unit loadout. */
export function cardsOf(...ids: CardCatalogId[]): CardDef[] {
  return ids.map(getCard);
}

export function allCardTemplates(): CardDef[] {
  return Object.values(CARD_CATALOG).map((card) => ({
    ...card,
    targets: [...card.targets],
  }));
}
