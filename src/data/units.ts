export const UNIT_BY_ID: Record<number, UnitDef> = Object.fromEntries(
  [...UNITS, ...TUTORIAL_UNITS].map((u) => [u.id, u]),
);

export function getUnitDef(id: number): UnitDef {
  const def = UNIT_BY_ID[id];
  if (!def) throw new Error(`Unknown unit: ${id}`);
  return def;
}
