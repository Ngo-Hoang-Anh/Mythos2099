function unit(opts: {
  id: number;
  class: UnitClass;
  hp: number;
  atk: number;
  armor: number;
  ap: number;
  cost: number;
  keywords: string;
  cards: UnitDef["cards"];
  hasArt?: boolean;
  displayType?: UnitDisplayType;
  name?: string;
  lore?: string;
  sfx?: UnitSfxSlots;
}): UnitDef {
  const identity = UNIT_IDENTITY[opts.id];
  return {
    id: opts.id,
    name: opts.name ?? identity?.name ?? String(opts.id),
    class: opts.class,
    hp: opts.hp,
    atk: opts.atk,
    armor: opts.armor,
    ap: opts.ap,
    cost: opts.cost,
    keywords: parseKeywords(opts.keywords),
    cards: opts.cards,
    lore: opts.lore ?? identity?.lore ?? "",
    hasArt: opts.hasArt ?? false,
    displayType: opts.displayType ?? "2d",
    sfx: opts.sfx ?? sfxSlotsForId(opts.id),
  };
}

