import type { UnitClass, UnitDef } from "../engine/types";
import { parseKeywords } from "../engine/keywords";
import { C, cardsOf } from "./cardCatalog";
import { TUTORIAL_UNITS } from "./tutorialUnits";
import { UNIT_IDENTITY } from "./unitLore";

function unit(opts: {
  id: number;
  class: UnitClass;
  hp: number;
  atk: number;
  armor: number;
  ap: number;
  cost: number;
  keywords: string;
  cards: UnitDef["cards"];
  hasArt?: boolean;
  name?: string;
  lore?: string;
}): UnitDef {
  const identity = UNIT_IDENTITY[opts.id];
  return {
    id: opts.id,
    name: opts.name ?? identity?.name ?? String(opts.id),
    class: opts.class,
    hp: opts.hp,
    atk: opts.atk,
    armor: opts.armor,
    ap: opts.ap,
    cost: opts.cost,
    keywords: parseKeywords(opts.keywords),
    cards: opts.cards,
    lore: opts.lore ?? identity?.lore ?? "",
    hasArt: opts.hasArt ?? false,
  };
}

